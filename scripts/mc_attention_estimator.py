"""Monte Carlo comparison of estimators of the attention spillover psi (Appendix A-ATT).

Simulates apartment markets whose index DiDs share the sampling error of the E-to-G group, as in
the paper's data, and compares the regression of the wedge through the origin with the
ratio-of-sums estimator, with and without the paper's selection of markets on beta1_hat > 0.

Calibration (no hand-typed data values):
  - market count, mean and variance of beta1_hat across all volume-filtered apartment markets,
    from src.event_study.compute_did on data/index_APARTMENT.csv (the population before selection);
  - registry belief e and energy-cost ratio eta from results/attention/summary.csv
    (run scripts/compute_attention.py first);
  - the noise share of Var(beta1_hat) is unknown and varied over NOISE_SHARES; total variance is
    held at its observed value, so signal variance = (1 - share) * observed variance.

Writes results/attention/mc_estimator.csv and results/tables/attention_mc_macros.tex (overwritten).

Usage
-----
    python scripts/mc_attention_estimator.py
"""
from __future__ import annotations

import logging
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.event_study import compute_did, load_price_indices  # noqa: E402

SEED: int = 20261008
TRUE_PSI: float = 0.15
N_REPS: int = 4000
NOISE_SHARES: tuple[float, ...] = (0.25, 0.50, 0.75)   # share of Var(beta1_hat) that is sampling noise


def calibration() -> dict[str, float]:
    """Population moments of beta1_hat (all volume-filtered markets) and aggregate e, eta."""
    idx = load_price_indices(str(ROOT / "data" / "index_APARTMENT.csv"), high_group="ABCD")
    did = compute_did(idx, min_volume=20).did
    b1 = 100.0 * did["DiD_beta1"].dropna()
    summ = pd.read_csv(ROOT / "results" / "attention" / "summary.csv", index_col="statistic")
    return dict(n_markets=int(len(b1)), b1_mean=float(b1.mean()), b1_var=float(b1.var(ddof=1)),
                e=float(summ.loc["e_w", "Apt"]), eta=float(summ.loc["eta_w", "Apt"]))


def simulate(rng: np.random.Generator, cal: dict[str, float], share: float,
             select: bool) -> tuple[float, float]:
    """Mean psi estimates (regression through origin, ratio of sums) over N_REPS samples."""
    m, e, eta = cal["n_markets"], cal["e"], cal["eta"]
    noise_var = share * cal["b1_var"]
    s_h = s_l = s_sil = np.sqrt(noise_var / 2.0)           # Var(eps_H - eps_L) = noise_var
    db = rng.normal(cal["b1_mean"], np.sqrt((1.0 - share) * cal["b1_var"]), size=(N_REPS, m))
    lam = (1 - TRUE_PSI) * db * (eta - e)                   # eq:att_lambda, C^def = 0
    delta = lam + e * db
    eps_h, eps_l, eps_s = (rng.normal(0.0, s, db.shape) for s in (s_h, s_l, s_sil))
    b1_hat = db + eps_h - eps_l                             # shared E-to-G error
    delta_hat = delta + eps_s - eps_l
    keep = b1_hat > 0 if select else np.ones_like(b1_hat, dtype=bool)
    y = np.where(keep, delta_hat - e * b1_hat, 0.0)
    x = np.where(keep, b1_hat * (eta - e), 0.0)
    psi_ols = 1.0 - (x * y).sum(axis=1) / (x * x).sum(axis=1)
    psi_rom = 1.0 - y.sum(axis=1) / x.sum(axis=1)
    return float(psi_ols.mean()), float(psi_rom.mean())


def main() -> None:
    logging.disable(logging.CRITICAL)
    cal = calibration()
    rng = np.random.default_rng(SEED)
    rows = []
    for share in NOISE_SHARES:
        for select in (False, True):
            ols, rom = simulate(rng, cal, share, select)
            rows.append(dict(noise_share=share, select_b1_positive=select, psi_true=TRUE_PSI,
                             psi_ols=ols, psi_rom=rom))
    res = pd.DataFrame(rows)
    out = ROOT / "results" / "attention"
    out.mkdir(parents=True, exist_ok=True)
    res.to_csv(out / "mc_estimator.csv", index=False)
    ns, sel = res[~res.select_b1_positive], res[res.select_b1_positive]
    macros = [
        "% Generated by scripts/mc_attention_estimator.py -- do not edit by hand.",
        f"\\newcommand{{\\attMCtrue}}{{{TRUE_PSI:.2f}}}",
        f"\\newcommand{{\\attMCmarkets}}{{{cal['n_markets']}}}",
        f"\\newcommand{{\\attMCshareLo}}{{{100 * min(NOISE_SHARES):.0f}}}",
        f"\\newcommand{{\\attMCshareHi}}{{{100 * max(NOISE_SHARES):.0f}}}",
        f"\\newcommand{{\\attMColsLo}}{{{ns.psi_ols.min():.2f}}}",
        f"\\newcommand{{\\attMColsHi}}{{{ns.psi_ols.max():.2f}}}",
        f"\\newcommand{{\\attMCromLo}}{{{ns.psi_rom.min():.2f}}}",
        f"\\newcommand{{\\attMCromHi}}{{{ns.psi_rom.max():.2f}}}",
        f"\\newcommand{{\\attMColsSelLo}}{{{sel.psi_ols.min():.2f}}}",
        f"\\newcommand{{\\attMColsSelHi}}{{{sel.psi_ols.max():.2f}}}",
        f"\\newcommand{{\\attMCromSelLo}}{{{sel.psi_rom.min():.2f}}}",
        f"\\newcommand{{\\attMCromSelHi}}{{{sel.psi_rom.max():.2f}}}",
    ]
    (ROOT / "results" / "tables" / "attention_mc_macros.tex").write_text("\n".join(macros) + "\n")
    print(f"calibration: {cal}")
    print(res.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
